export type LayerId =
  | 'user_io'
  | 'core_engine'
  | 'module_layer'
  | 'external_services'
  | 'data_models';

export type TopologyMode = 'corrected' | 'original' | 'diff';

export type NodeAnomalyStatus = 'nominal' | 'orphaned' | 'bottleneck' | 'miswired' | 'rebranded';

export interface ArchitectureLayer {
  id: LayerId;
  index: string;
  title: string;
  subtitle: string;
  y: number;
  height: number;
  x: number;
  width: number;
  surfaceBg: string;
  borderHex: string;
  nodeFillHex: string;
  nodeBorderHex: string;
  nodeTextHex: string;
}

export interface ArchitectureNode {
  id: string;
  label: string;
  originalLabel?: string;
  layer: LayerId;
  subGroup?: string;
  x: number;
  y: number;
  width: number;
  height: number;
  role: string;
  description: string;
  pythonDependencies: string[];
  anomalyStatus: NodeAnomalyStatus;
  originalAnomalyNote?: string;
  ferrumFixNote?: string;
}

export type EdgeStatus = 'original' | 'misrouted' | 'repaired';

export interface ArchitectureEdge {
  id: string;
  source: string;
  target: string;
  label?: string;
  bidirectional?: boolean;
  status: EdgeStatus;
  protocol: string;
  explanation: string;
}

export interface TraceStep {
  stepIndex: number;
  activeNodeId: string;
  activeEdgeId?: string;
  layer: LayerId;
  actionTitle: string;
  description: string;
  payloadSample: string;
  stateMutation: string;
  latencyMs: number;
}

export interface CommandTraceScenario {
  id: string;
  title: string;
  voiceUtterance: string;
  category: string;
  requiresCorrectedTopology: boolean;
  brokenInOriginalReason?: string;
  summary: string;
  steps: TraceStep[];
}

export interface AnomalyAuditItem {
  id: string;
  title: string;
  severity: 'Critical Orphan' | 'Misrouted Edge' | 'Architectural Bottleneck' | 'Core Rebrand';
  affectedNodeIds: string[];
  affectedEdgeIds: string[];
  rawDiagramBehavior: string;
  correctedFerrumBehavior: string;
  architecturalRationale: string;
}

